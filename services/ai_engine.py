"""
Простой, но эффективный AI-движок для автоответов и консультаций.
Можно легко заменить на OpenAI / Groq / xAI API.
"""

async def generate_reply(user_text: str, user_id: int = None) -> str:
    text = user_text.lower().strip()

    # Базовые бизнес-ответы
    if any(w in text for w in ["цена", "стоимость", "сколько стоит", "прайс"]):
        return (
            "Спасибо за интерес! Стоимость зависит от объёма и задач.\n"
            "Оставьте заявку через меню «Оставить заявку» — и я подготовлю точный расчёт."
        )

    if any(w in text for w in ["услуг", "что вы делаете", "чем занимаетесь", "помощь"]):
        return (
            "Я — Business Ai, AI-помощник для бизнеса.\n\n"
            "Помогаю:\n"
            "• Автоматически отвечать клиентам 24/7\n"
            "• Проводить консультации\n"
            "• Создавать и публиковать посты\n"
            "• Собирать и обрабатывать заявки\n\n"
            "Напишите, какая задача у вас стоит — подскажу решение."
        )

    if any(w in text for w in ["привет", "здравствуй", "добрый", "hello", "hi"]):
        return (
            "Здравствуйте! Я Business Ai — ваш помощник по бизнесу.\n"
            "Могу ответить на вопросы, проконсультировать или принять заявку.\n"
            "Чем могу помочь прямо сейчас?"
        )

    if any(w in text for w in ["заявк", "оставить", "хочу", "нужно", "интересует"]):
        return (
            "Отлично! Нажмите кнопку «Оставить заявку» в меню или напишите /lead — "
            "я быстро оформлю всё."
        )

    # Универсальный ответ
    return (
        f"Понял ваш запрос: «{user_text[:80]}...»\n\n"
        "Я могу:\n"
        "• Дать консультацию — нажмите «Консультация»\n"
        "• Принять заявку — «Оставить заявку»\n"
        "• Создать пост — «Создать пост»\n\n"
        "Или просто уточните вопрос — отвечу подробнее."
    )

async def generate_consultation(question: str) -> str:
    q = question.lower()

    if "маркетинг" in q or "реклам" in q:
        return (
            "<b>Консультация по маркетингу</b>\n\n"
            "Ключевые шаги:\n"
            "1. Определите целевую аудиторию и боли\n"
            "2. Выберите 1–2 канала (Telegram + таргет / SEO)\n"
            "3. Создавайте полезный контент регулярно\n"
            "4. Собирайте заявки через бота (как этот)\n"
            "5. Анализируйте конверсию и улучшайте\n\n"
            "Хотите, подготовлю план под вашу нишу? Оставьте заявку."
        )

    if "продаж" in q or "клиент" in q:
        return (
            "<b>Консультация по продажам</b>\n\n"
            "• Автоответы 24/7 повышают скорость реакции → больше сделок\n"
            "• Собирайте заявки сразу в боте\n"
            "• Используйте прогрев через посты\n"
            "• Всегда предлагайте следующий шаг\n\n"
            "Могу настроить под ваш бизнес. Напишите детали в заявке."
        )

    return (
        f"<b>Консультация по запросу:</b>\n\n«{question}»\n\n"
        "Рекомендую:\n"
        "1. Чётко сформулировать цель\n"
        "2. Разбить на этапы\n"
        "3. Автоматизировать рутину (боты, CRM)\n"
        "4. Измерять результат\n\n"
        "Для более точной консультации оставьте заявку — разберём вашу ситуацию детально."
    )
